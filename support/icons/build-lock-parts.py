#!/usr/bin/env python3
# build-lock-parts.py [repo] [greeter SymbolPaths.js]: writes lucidlock/parts/symbols.js and shapes.js: the material symbols and
# m3 shapes the shared lock parts draw, cut from the shell's own tables so the
# greeter (which cannot import the shell) draws the very same outlines
import json, re, sys, os

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
greeter_tab = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "support/sddm/lucid/components/SymbolPaths.js")
NAMES = """lock lock_open key arrow_forward check close visibility visibility_off
keyboard_capslock signal_wifi_4_bar signal_wifi_off network_wifi_1_bar network_wifi_2_bar
network_wifi_3_bar lan bluetooth bluetooth_disabled bluetooth_connected
battery_0_bar battery_1_bar battery_2_bar battery_3_bar battery_4_bar battery_5_bar
battery_6_bar battery_full battery_charging_full notifications notifications_off
do_not_disturb_on power_settings_new restart_alt logout bedtime ac_unit keyboard
computer fingerprint info schedule event music_note person desktop_windows
expand_more arrow_back person_add favorite home call mail star alarm timer add
drag_indicator backspace keyboard_return shift keyboard_arrow_down
keyboard_tab chevron_left chevron_right keyboard_arrow_up remove skip_previous play_pause
skip_next volume_off volume_down volume_up brightness_low brightness_high
""".split()
WEATHER = "clear_day clear_night partly_cloudy_day partly_cloudy_night cloud rainy weather_snowy thunderstorm foggy".split()

def table(path, var):
    src = open(path).read()
    for line in src.split("\n"):
        if line.startswith("var %s = " % var):
            return json.loads(line[len("var %s = " % var):].rstrip(";"))
    return {}

shell = table(os.path.join(root, "lucidui/SymbolPaths.js"), "p")
parts = table(os.path.join(root, "lucidui/SymbolPaths.js"), "parts")
greet = table(greeter_tab, "p") if greeter_tab else {}
out, missing = {}, []
for n in NAMES + WEATHER:
    v = shell.get(n)
    if isinstance(v, list) and v:
        out[n] = v[1] if len(v) > 1 and v[1] else v[0]
    elif isinstance(v, str):
        out[n] = v
    elif n in greet:
        out[n] = greet[n] if isinstance(greet[n], str) else greet[n][-1]
    else:
        missing.append(n)
if missing:
    sys.exit("missing symbols: " + " ".join(missing))
wparts = {k: parts[k] for k in WEATHER if k in parts}
dst = os.path.join(root, "lucidlock/parts")
with open(os.path.join(dst, "symbols.js"), "w") as f:
    f.write(".pragma library\n// generated by support/icons/build-lock-parts.py from lucidui/SymbolPaths.js — do not edit\n")
    f.write("var p = " + json.dumps(out, separators=(",", ":")) + ";\n")
    f.write("var parts = " + json.dumps(wparts, separators=(",", ":")) + ";\n")
src = open(os.path.join(root, "lucidui/ShapeRadii.js")).read()
src = src.replace("// generated by support/shapes/build-shapes.py", "// copied from lucidui/ShapeRadii.js (support/shapes/build-shapes.py)")
with open(os.path.join(dst, "shapes.js"), "w") as f:
    f.write(src)
print("symbols", len(out), "weather parts", len(wparts))
